@app.get("/api/v1/soc/latest-report", tags=["SOC"])
async def get_latest_report():
    if not SOC_REPORT_PATH.exists():
        return {"message": "No reports available"}
    try:
        return json.loads(SOC_REPORT_PATH.read_text(encoding="utf-8"))
    except Exception as exc:
        raise HTTPException(status_code=500, detail=f"Failed to load latest SOC report: {exc}") from exc


@app.get("/api/v1/soc/alerts", tags=["SOC"])
def list_soc_alerts(limit: int = Query(default=50, ge=1, le=500)) -> Dict[str, Any]:
    _sync_output_data()
    items = list(reversed(soc_alert_history))[:limit]
    return {
        "total": len(soc_alert_history),
        "count": len(items),
        "items": items,
    }


@app.get("/api/v1/soc/alerts/{alert_id}", tags=["SOC"])
def get_soc_alert(alert_id: str) -> Dict[str, Any]:
    _sync_output_data()
    for alert in reversed(soc_alert_history):
        if alert.get("alert_id") == alert_id:
            return alert
    raise HTTPException(status_code=404, detail=f"SOC alert {alert_id} not found")


@app.patch("/api/v1/soc/alerts/{alert_id}/status", tags=["SOC"])
async def update_soc_alert_status(alert_id: str, request: Request) -> Dict[str, Any]:
    try:
        incoming = await request.json()
        if not isinstance(incoming, dict):
            raise HTTPException(status_code=400, detail="JSON body must be an object")

        status = str(incoming.get("status", "")).strip().lower()
        decision = str(incoming.get("decision") or status).strip()
        return _update_alert_status(alert_id, status, decision)
    except HTTPException:
        raise
    except Exception as exc:
        raise HTTPException(status_code=500, detail=str(exc)) from exc


@app.get("/api/v1/soc/dashboard/summary", tags=["Dashboard"])
def dashboard_summary() -> Dict[str, Any]:
    _sync_output_data()
    risk_distribution = {"CRITICAL": 0, "HIGH": 0, "MEDIUM": 0, "LOW": 0, "NONE": 0}
    type_distribution: Dict[str, int] = {}
    router_distribution: Dict[str, int] = {}
    status_distribution: Dict[str, int] = {}

    for alert in soc_alert_history:
        risk_level = alert.get("risk_level", "NONE")
        if risk_level not in risk_distribution:
            risk_level = "NONE"
        risk_distribution[risk_level] += 1

        alert_type = str(alert.get("alert_type", "unknown"))
        type_distribution[alert_type] = type_distribution.get(alert_type, 0) + 1
        router_name = str(alert.get("router_name") or "direct_ingest")
        router_distribution[router_name] = router_distribution.get(router_name, 0) + 1
        status = str(alert.get("status") or "unknown")
        status_distribution[status] = status_distribution.get(status, 0) + 1

    return {
        "summary": {
            "total_alerts": len(soc_alert_history),
            "critical_alerts": risk_distribution["CRITICAL"],
            "high_alerts": risk_distribution["HIGH"],
            "successful_outputs": status_distribution.get("success", 0),
            "latest_alert_id": soc_alert_history[-1]["alert_id"] if soc_alert_history else None,
            "latest_timestamp": soc_alert_history[-1]["timestamp"] if soc_alert_history else None,
        },
        "risk_distribution": risk_distribution,
        "type_distribution": type_distribution,
        "router_distribution": router_distribution,
        "status_distribution": status_distribution,
    }


@app.get("/dashboard", tags=["Dashboard"])
def serve_dashboard() -> FileResponse:
    dashboard_file = UI_DIR / "dashboard.html"
    if not dashboard_file.exists():
        raise HTTPException(status_code=404, detail="Dashboard UI not found")
    return FileResponse(dashboard_file)


@app.get("/dashboard/assets/{asset_name}", tags=["Dashboard"])
def serve_dashboard_asset(asset_name: str) -> FileResponse:
    safe_name = Path(asset_name).name
    file_path = UI_DIR / safe_name
    if not file_path.exists() or not file_path.is_file():
        raise HTTPException(status_code=404, detail=f"Asset {safe_name} not found")
    return FileResponse(file_path)


