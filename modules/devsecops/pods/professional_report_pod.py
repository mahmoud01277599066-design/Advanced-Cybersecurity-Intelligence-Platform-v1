"""
DevSecOps Module - Professional Report Pod
Generates a human-ready, executive security audit report in Markdown format.
"""

import os
from datetime import datetime, timezone
from typing import Dict, Any, List
from ..core_orchestrator.state_schema import DevSecOpsState
from ..core_orchestrator.model_router import model_router
from ..src.core.logger import get_logger

logger = get_logger(__name__)


def generate_markdown_report(findings: List[Dict[str, Any]], stats: Dict[str, Any]) -> str:
    """
    Combine AI analysis and findings into a professional Markdown document.
    """
    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    
    # Building findings list for prompt
    findings_summary = ""
    for idx, f in enumerate(findings, 1):
        findings_summary += f"### Finding {idx}: {f.get('finding_id')}\n"
        findings_summary += f"- **Severity:** {f.get('tool_severity')} / 10\n"
        findings_summary += f"- **File:** {f.get('file_path')}\n"
        findings_summary += f"- **Description:** {f.get('message')}\n\n"

    # Context for AI Report Writer
    context = {
        "findings_summary": findings_summary,
        "actions_summary": f"Scanned {stats.get('total_files_scanned', 0)} files in target directory.",
        "remediation_status": "PENDING_REVIEW",
    }
    
    # Use AI to generate executive summary and report structure
    ai_report_content = model_router.route("report_generation", context)
    
    # Final assembly
    report = f"""# ACIP SECURITY AUDIT REPORT
**Target:** {stats.get('directory_path', 'Source Code')}
**Date:** {timestamp}
**Total Findings:** {len(findings)}

---

{ai_report_content}

---
*Report generated by ACIP DevSecOps Grand Orchestrator - Professional Reporting Agent.*
"""
    return report


def professional_report_node(state: DevSecOpsState) -> Dict[str, Any]:
    """
    Pod Node: Generate a professional security audit report.
    """
    findings = state.get("parsed_findings", [])
    data_payload = state.get("data_payload", {})
    
    thought_process = "[Professional Report Pod] Aggregating findings into executive report. "
    
    if not findings:
        thought_process += "No findings detected. Generating a clean report."
    
    report_md = generate_markdown_report(findings, data_payload)
    
    # Save report to file (Real-world action)
    report_filename = "SECURITY_AUDIT_REPORT.md"
    try:
        with open(report_filename, "w", encoding='utf-8') as f:
            f.write(report_md)
        thought_process += f"Report successfully saved to {report_filename}."
    except Exception as e:
        logger.error(f"Failed to save report: {e}")
        thought_process += f"Error saving report to disk: {e}"

    logger.info(f"[Professional Report Pod] Report generated: {report_filename}")

    return {
        "pod_name": "professional_report_pod",
        "remediation_status": "REPORT_GENERATED",
        "ai_thought_process": thought_process,
        "human_approval_required": False,
        "data_payload": {
            **data_payload,
            "report_path": report_filename,
            "report_preview": report_md[:200] + "..."
        },
        "messages": state.get("messages", []) + [
            f"[Professional Report] Generated executive audit report: {report_filename}"
        ],
    }
