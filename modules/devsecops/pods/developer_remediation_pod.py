"""
DevSecOps Module - Developer Remediation Pod
Specialize in generating technical security guidance for software developers.
Focuses on CWE references, impact analysis, and secure coding patterns.
"""

import os
from datetime import datetime, timezone
from typing import Dict, Any, List
from ..core_orchestrator.state_schema import DevSecOpsState
from ..core_orchestrator.model_router import model_router
from ..src.core.logger import get_logger

logger = get_logger(__name__)


def generate_technical_guidance(findings: List[Dict[str, Any]]) -> str:
    """
    Use AI to transform findings into a technical developer guide.
    """
    if not findings:
        return "No vulnerabilities detected. No remediation required."

    # Building context for the AI Advisor
    findings_context = ""
    for idx, f in enumerate(findings, 1):
        findings_context += f"--- FINDING {idx} ---\n"
        findings_context += f"ID: {f.get('finding_id')}\n"
        findings_context += f"File: {f.get('file_path')}\n"
        findings_context += f"Criticality: {f.get('tool_severity')}\n"
        findings_context += f"AI Analysis: {f.get('message')}\n\n"

    # Define the System Prompt for a Security Consultant
    prompt = (
        "You are a Senior Security Consultant. Create a TECHNICAL REMEDIATION GUIDE for developers "
        "based on the following findings. For each finding, include:\n"
        "1. **Technical Deep Dive**: Explain how the vulnerability works at the code level.\n"
        "2. **Real-world Impact**: What could a hacker actually achieve?\n"
        "3. **Remediation Steps**: Step-by-step technical fix.\n"
        "4. **Secure Code Snippet**: Provide a 'Corrected Version' of the code.\n"
        "5. **CWE Reference**: Link to relevant CWE (Common Weakness Enumeration).\n"
        "6. **Prevention Principles**: How to avoid this in the future.\n"
        "Make it highly technical and professional.\n\n"
        f"Findings Context:\n{findings_context}"
    )

    # Invoke AI via model_router (task: report_generation for structure)
    ai_guide = model_router.route("report_generation", {
        "findings_summary": prompt,
        "actions_summary": "Technical analysis of Command Injection vulnerability.",
        "remediation_status": "PENDING_DEVELOPER_FIX"
    })
    
    return ai_guide


def developer_remediation_node(state: DevSecOpsState) -> Dict[str, Any]:
    """
    Pod Node: Generate a deep-dive remediation guide for developers.
    """
    findings = state.get("parsed_findings", [])
    data_payload = state.get("data_payload", {})
    
    thought_process = "[Developer Remediation Pod] Translating findings into technical developer guidance. "
    
    if not findings:
        thought_process += "No findings to report."
        return {
            "pod_name": "developer_remediation_pod",
            "remediation_status": "SKIPPED",
            "ai_thought_process": thought_process,
            "data_payload": {**data_payload, "remediation_report_path": None}
        }

    # Generate Markdown Guide
    guide_content = generate_technical_guidance(findings)
    
    # Final Doc Assembly
    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S")
    report_md = f"""# 🛡️ ACIP DEVELOPER REMEDIATION GUIDE
**Date:** {timestamp}
**Target Module:** {data_payload.get('directory_path', 'N/A')}

---

{guide_content}

---
*Generated by ACIP DevSecOps - Technical AI Security Consultant.*
"""

    # Persistent Storage (Real-world action)
    report_filename = "DEVELOPER_REMEDIATION_GUIDE.md"
    try:
        with open(report_filename, "w", encoding='utf-8') as f:
            f.write(report_md)
        thought_process += f"Technical guide saved to {report_filename}."
    except Exception as e:
        logger.error(f"Failed to save technical guide: {e}")
        thought_process += f"Error saving file: {e}"

    logger.info(f"[Developer Remediation Pod] Technical guide generated: {report_filename}")

    return {
        "pod_name": "developer_remediation_pod",
        "remediation_status": "DEVELOPER_GUIDE_GENERATED",
        "ai_thought_process": thought_process,
        "human_approval_required": False,
        "data_payload": {
            **data_payload,
            "remediation_report_path": report_filename,
            "remediation_preview": report_md[:250] + "..."
        },
        "messages": state.get("messages", []) + [
            f"[Developer Remediation] Generated technical guidance for {len(findings)} findings."
        ],
    }
